export const LEGACY_TABLES = [
  'settings',
  'schedules',
  'departments',
  'employees',
  'schedule_versions',
  'employee_schedules',
  'users',
  'notification_reads',
  'attendance',
  'attendance_evidence',
  'audit',
  'attendance_location',
  'employee_requests',
  'payroll_runs',
  'payroll_deductions',
  'sales_activities',
  'sales_targets',
] as const;

export const TRANSIENT_TABLES = ['sessions', 'login_limits'] as const;

export const TENANT_TABLES = [
  'branches',
  'employee_branches',
  'hr_branch_grants',
  ...LEGACY_TABLES,
  ...TRANSIENT_TABLES,
] as const;

const scope = `company_id uuid NOT NULL REFERENCES companies(id),
  row_order bigint GENERATED BY DEFAULT AS IDENTITY,
  UNIQUE(company_id, row_order)`;

export const INITIAL_SCHEMA = `
  REVOKE CREATE ON SCHEMA public FROM PUBLIC;
  CREATE TABLE companies (
    id uuid PRIMARY KEY, workspace_code text NOT NULL,
    name text NOT NULL, timezone text NOT NULL,
    status text NOT NULL CHECK(status IN ('provisioning','active','suspended','archived')),
    created_at timestamptz NOT NULL DEFAULT now()
  );
  CREATE UNIQUE INDEX companies_workspace ON companies(lower(workspace_code));
  CREATE TABLE branches (
    ${scope}, id uuid NOT NULL, code text NOT NULL, name text NOT NULL,
    active boolean NOT NULL DEFAULT true, policy text NOT NULL,
    PRIMARY KEY(company_id, id)
  );
  CREATE UNIQUE INDEX branches_code ON branches(company_id, lower(code));
  CREATE TABLE settings (
    ${scope}, key text NOT NULL, value text NOT NULL, PRIMARY KEY(company_id, key)
  );
  CREATE TABLE schedules (
    ${scope}, id text NOT NULL, data text NOT NULL, PRIMARY KEY(company_id, id)
  );
  CREATE TABLE departments (
    ${scope}, name text NOT NULL, PRIMARY KEY(company_id, name)
  );
  CREATE UNIQUE INDEX departments_name ON departments(company_id, lower(name));
  CREATE TABLE employees (
    ${scope}, id text NOT NULL, code text NOT NULL, email text NOT NULL,
    employee_number text NOT NULL, manager_id text, data text NOT NULL,
    PRIMARY KEY(company_id, id),
    FOREIGN KEY(company_id, manager_id) REFERENCES employees(company_id, id)
      DEFERRABLE INITIALLY DEFERRED
  );
  CREATE UNIQUE INDEX employees_code ON employees(company_id, lower(code));
  CREATE UNIQUE INDEX employees_email ON employees(company_id, lower(email));
  CREATE UNIQUE INDEX employees_number ON employees(company_id, employee_number);
  CREATE INDEX employees_manager ON employees(company_id, manager_id);
  CREATE TABLE employee_branches (
    ${scope}, employee_id text NOT NULL, branch_id uuid NOT NULL,
    effective_from text NOT NULL, PRIMARY KEY(company_id, employee_id, effective_from),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id),
    FOREIGN KEY(company_id, branch_id) REFERENCES branches(company_id, id)
  );
  CREATE TABLE schedule_versions (
    ${scope}, schedule_id text NOT NULL, effective_from text NOT NULL, data text NOT NULL,
    PRIMARY KEY(company_id, schedule_id, effective_from),
    FOREIGN KEY(company_id, schedule_id) REFERENCES schedules(company_id, id)
  );
  CREATE TABLE employee_schedules (
    ${scope}, employee_id text NOT NULL, effective_from text NOT NULL, schedule_id text NOT NULL,
    PRIMARY KEY(company_id, employee_id, effective_from),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id),
    FOREIGN KEY(company_id, schedule_id) REFERENCES schedules(company_id, id)
  );
  CREATE TABLE users (
    ${scope}, id text NOT NULL, email text NOT NULL, name text NOT NULL,
    role text NOT NULL CHECK(role IN ('employee','manager','hr','admin')),
    employee_id text, active integer NOT NULL CHECK(active IN (0,1)), password_hash text NOT NULL,
    PRIMARY KEY(company_id, id), UNIQUE(company_id, employee_id),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id)
  );
  CREATE UNIQUE INDEX users_email ON users(company_id, lower(email));
  CREATE TABLE hr_branch_grants (
    ${scope}, user_id text NOT NULL, branch_id uuid NOT NULL,
    PRIMARY KEY(company_id, user_id, branch_id),
    FOREIGN KEY(company_id, user_id) REFERENCES users(company_id, id),
    FOREIGN KEY(company_id, branch_id) REFERENCES branches(company_id, id)
  );
  CREATE TABLE notification_reads (
    ${scope}, user_id text NOT NULL, notification_id text NOT NULL, read_at text NOT NULL,
    PRIMARY KEY(company_id, user_id, notification_id),
    FOREIGN KEY(company_id, user_id) REFERENCES users(company_id, id)
  );
  CREATE TABLE sessions (
    ${scope}, hash text NOT NULL, user_id text NOT NULL, expires text NOT NULL,
    PRIMARY KEY(company_id, hash),
    FOREIGN KEY(company_id, user_id) REFERENCES users(company_id, id)
  );
  CREATE TABLE login_limits (
    ${scope}, email text NOT NULL, failures integer NOT NULL, reset_at bigint NOT NULL,
    PRIMARY KEY(company_id, email)
  );
  CREATE TABLE attendance (
    ${scope}, id text NOT NULL, employee_id text NOT NULL,
    work_date text NOT NULL, check_in text NOT NULL, check_out text,
    schedule text NOT NULL, timezone text NOT NULL,
    branch_id uuid NOT NULL, branch_snapshot text NOT NULL,
    PRIMARY KEY(company_id, id), UNIQUE(company_id, employee_id, work_date),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id),
    FOREIGN KEY(company_id, branch_id) REFERENCES branches(company_id, id)
  );
  CREATE TABLE attendance_evidence (
    ${scope}, attendance_id text NOT NULL,
    event text NOT NULL CHECK(event IN ('check-in','check-out')),
    latitude double precision NOT NULL, longitude double precision NOT NULL,
    accuracy_meters double precision NOT NULL, distance_meters double precision NOT NULL,
    captured_at text NOT NULL, submitted_at text NOT NULL, policy text NOT NULL, photo bytea NOT NULL,
    PRIMARY KEY(company_id, attendance_id, event),
    FOREIGN KEY(company_id, attendance_id) REFERENCES attendance(company_id, id)
  );
  CREATE TABLE audit (
    ${scope}, id text NOT NULL, actor_id text NOT NULL, actor_name text NOT NULL,
    action text NOT NULL, record_id text NOT NULL, at text NOT NULL,
    reason text, before_data text, after_data text, PRIMARY KEY(company_id, id),
    FOREIGN KEY(company_id, actor_id) REFERENCES users(company_id, id)
  );
  CREATE INDEX audit_record ON audit(company_id, record_id);
  CREATE INDEX audit_actor ON audit(company_id, actor_id);
  CREATE INDEX audit_date ON audit(company_id, at);
  CREATE TABLE attendance_location (
    ${scope}, attendance_id text NOT NULL, data text NOT NULL,
    PRIMARY KEY(company_id, attendance_id),
    FOREIGN KEY(company_id, attendance_id) REFERENCES attendance(company_id, id)
  );
  CREATE TABLE employee_requests (
    ${scope}, id text NOT NULL, employee_id text NOT NULL,
    status text NOT NULL CHECK(status IN ('pending','approved','rejected','withdrawn')),
    data text NOT NULL, PRIMARY KEY(company_id, id),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id)
  );
  CREATE INDEX requests_employee ON employee_requests(company_id, employee_id, status);
  CREATE INDEX requests_status ON employee_requests(company_id, status);
  CREATE TABLE payroll_runs (
    ${scope}, month text NOT NULL, data text NOT NULL, PRIMARY KEY(company_id, month)
  );
  CREATE TABLE payroll_deductions (
    ${scope}, id text NOT NULL, employee_id text NOT NULL, month text NOT NULL, data text NOT NULL,
    PRIMARY KEY(company_id, id),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id)
  );
  CREATE INDEX deductions_month ON payroll_deductions(company_id, month, employee_id);
  CREATE TABLE sales_activities (
    ${scope}, id text NOT NULL, employee_id text NOT NULL, activity_date text NOT NULL,
    deal_reference text, data text NOT NULL, PRIMARY KEY(company_id, id),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id)
  );
  CREATE UNIQUE INDEX sales_reference ON sales_activities(company_id, lower(deal_reference));
  CREATE INDEX sales_date ON sales_activities(company_id, employee_id, activity_date);
  CREATE TABLE sales_targets (
    ${scope}, employee_id text NOT NULL, month text NOT NULL, data text NOT NULL,
    PRIMARY KEY(company_id, employee_id, month),
    FOREIGN KEY(company_id, employee_id) REFERENCES employees(company_id, id)
  );
  ALTER TABLE companies ENABLE ROW LEVEL SECURITY;
  ALTER TABLE companies FORCE ROW LEVEL SECURITY;
  CREATE POLICY company_scope ON companies
    USING (id = nullif(current_setting('hr.company_id', true), '')::uuid)
    WITH CHECK (id = nullif(current_setting('hr.company_id', true), '')::uuid);
  ${TENANT_TABLES.map(
    (table) => `
    ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;
    ALTER TABLE ${table} FORCE ROW LEVEL SECURITY;
    CREATE POLICY company_scope ON ${table}
      USING (company_id = nullif(current_setting('hr.company_id', true), '')::uuid)
      WITH CHECK (company_id = nullif(current_setting('hr.company_id', true), '')::uuid);
  `,
  ).join('\n')}
`;
