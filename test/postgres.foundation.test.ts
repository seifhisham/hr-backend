it('backs up and imports all durable tables byte-for-byte without changing SQLite', async () => {
  const source = fixture('complete');
  const before = readFileSync(source);
  const report = await importSqlite(
    migration,
    options(source, 'complete-backup.sqlite'),
  );
  expect(readFileSync(source)).toEqual(before);
  expect(Object.keys(report.counts)).toEqual([...LEGACY_TABLES]);
  expect(Object.values(report.counts).every((n) => n > 0)).toBe(true);
  expect(report.revokedSessions).toBe(1);
  expect(report.resetLoginLimits).toBe(1);
  expect((await migration.query('SELECT * FROM sessions')).rowCount).toBe(0);
  expect((await migration.query('SELECT * FROM login_limits')).rowCount).toBe(
    0,
  );
  expect(
    (await migration.query("SELECT password_hash FROM users WHERE id='user'"))
      .rows[0].password_hash,
  ).toBe('keep:exact:hash');
  expect(
    (await migration.query('SELECT photo FROM attendance_evidence')).rows[0]
      .photo,
  ).toEqual(Buffer.from([0, 1, 255, 128]));
  expect(
    (await migration.query('SELECT data FROM payroll_runs')).rows[0].data,
  ).toBe('{ "status": "approved", "rows": [{"netSalary":1234.50}] }');
  const location = JSON.parse(
    (await migration.query('SELECT data FROM attendance_location')).rows[0]
      .data,
  );
  expect(location).toMatchObject({
    status: 'unavailable',
    returnBy: null,
    lastCapturedAt: null,
  });
  expect(
    (await migration.query('SELECT status FROM companies')).rows[0].status,
  ).toBe('provisioning');
  expect(
    (await migration.query('SELECT * FROM employee_branches')).rowCount,
  ).toBe(1);
  expect(
    (await migration.query('SELECT user_id FROM hr_branch_grants')).rows,
  ).toEqual([{ user_id: 'hr' }]);
  await expect(
    importSqlite(migration, options(source, 'complete-backup.sqlite')),
  ).rejects.toMatchObject({ code: 'EEXIST' });
  await expect(
    importSqlite(migration, options(source, 'retry-backup.sqlite')),
  ).rejects.toThrow('empty target');
  expect((await migration.query('SELECT * FROM employees')).rowCount).toBe(1);
});

it('keeps a verified backup and rolls back the whole import on malformed or orphaned data', async () => {
  const source = fixture('invalid');
  const db = new DatabaseSync(source);
  db.prepare(
    "UPDATE employees SET data=json_set(data,'$.managerId','nonexistent')",
  ).run();
  db.close();
  const before = readFileSync(source);
  const input = options(source, 'invalid-backup.sqlite');
  await expect(importSqlite(migration, input)).rejects.toMatchObject({
    code: '23503',
  });
  expect((await migration.query('SELECT * FROM companies')).rowCount).toBe(0);
  expect((await migration.query('SELECT * FROM employees')).rowCount).toBe(0);
  const backup = new DatabaseSync(input.backup, { readOnly: true });
  expect(backup.prepare('PRAGMA integrity_check').get()!.integrity_check).toBe(
    'ok',
  );
  expect(
    JSON.parse(String(backup.prepare('SELECT data FROM employees').get()!.data))
      .managerId,
  ).toBe('nonexistent');
  backup.close();
  expect(readFileSync(source)).toEqual(before);
});

it('backs up committed WAL data while the source stays open, without changing source data', async () => {
  const source = fixture('wal');
  const writer = new DatabaseSync(source);
  try {
    writer
      .prepare(
        "UPDATE settings SET value='43' WHERE key='employee_number_sequence'",
      )
      .run();
    const mainBefore = readFileSync(source);
    const walBefore = readFileSync(`${source}-wal`);
    const report = await importSqlite(
      migration,
      options(source, 'wal-backup.sqlite'),
    );
    expect(
      (
        await migration.query(
          "SELECT value FROM settings WHERE key='employee_number_sequence'",
        )
      ).rows[0].value,
    ).toBe('43');
    expect(readFileSync(source)).toEqual(mainBefore);
    expect(readFileSync(`${source}-wal`)).toEqual(walBefore);
    const backup = new DatabaseSync(report.backup, { readOnly: true });
    try {
      expect(
        backup
          .prepare(
            "SELECT value FROM settings WHERE key='employee_number_sequence'",
          )
          .get()!.value,
      ).toBe('43');
    } finally {
      backup.close();
    }
  } finally {
    writer.close();
  }
});
