const adminUrl = process.env.HR_PG_TEST_ADMIN_URL;
if (!adminUrl)
  throw new Error(
    'Set HR_PG_TEST_ADMIN_URL to a local development administrator URL; tests create/drop a separate database',
  );
const suffix = randomBytes(8).toString('hex');
const database = `hr_foundation_test_${suffix}`;
const role = `hr_test_${suffix}`;
const password = randomBytes(32).toString('hex');
const admin = new Pool({ connectionString: adminUrl });
let migration: Pool;
let runtime: Pool;
let store: PostgresStore;
let concurrentStore: PostgresStore;
const directory = mkdtempSync(join(tmpdir(), 'hr-pg-foundation-'));
if (
  dirname(directory) !== resolve(tmpdir()) ||
  !basename(directory).startsWith('hr-pg-foundation-')
)
  throw new Error(
    'Refusing cleanup outside the generated temporary test directory',
  );
const companyA = randomUUID();
const companyB = randomUUID();
const branchA = randomUUID();
const branchB = randomUUID();

beforeAll(async () => {
  await admin.query(`CREATE DATABASE ${database}`);
  const url = new URL(adminUrl);
  url.pathname = `/${database}`;
  migration = new Pool({ connectionString: url.href });
  await migrate(migration);
  await admin.query(
    `CREATE ROLE ${role} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS`,
  );
  const sql = await admin.query(
    "SELECT format('ALTER ROLE %I PASSWORD %L',$1::text,$2::text) AS sql",
    [role, password],
  );
  await admin.query(sql.rows[0].sql);
  await migration.query(`GRANT USAGE ON SCHEMA public TO ${role}`);
  await migration.query(
    `GRANT SELECT,INSERT,UPDATE,DELETE ON companies,${TENANT_TABLES.join(',')} TO ${role}`,
  );
  await migration.query(
    `GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO ${role}`,
  );
  for (const signature of [
    ...BRANCH_FUNCTIONS,
    ...OWNER_FUNCTIONS,
    ...BRANCH_LIMIT_FUNCTIONS,
  ])
    await migration.query(`GRANT EXECUTE ON FUNCTION ${signature} TO ${role}`);
  url.username = role;
  url.password = password;
  runtime = new Pool({ connectionString: url.href, max: 1 });
  store = new PostgresStore({ connectionString: url.href, max: 1 });
  concurrentStore = new PostgresStore({ connectionString: url.href, max: 4 });
});

beforeEach(async () => {
  await migration.query(
    `TRUNCATE companies,${TENANT_TABLES.join(',')} RESTART IDENTITY CASCADE`,
  );
});

afterAll(async () => {
  await store?.close();
  await concurrentStore?.close();
  await runtime?.end();
  await migration?.end();
  try {
    // Names are generated by this suite; never drop a user-supplied database.
    await admin.query(`DROP DATABASE IF EXISTS ${database}`);
    await admin.query(`DROP ROLE IF EXISTS ${role}`);
  } finally {
    await admin.end();
    rmSync(directory, { recursive: true, force: true });
  }
});

async function seed() {
  for (const [company, branch] of [
    [companyA, branchA],
    [companyB, branchB],
  ]) {
    await migration.query(
      `INSERT INTO companies(id,workspace_code,name,timezone,status)
      VALUES($1,$2,'Company','Africa/Cairo','active')`,
      [company, company],
    );
    await migration.query(
      `INSERT INTO branches(company_id,id,code,name,policy)
      VALUES($1,$2,'main','Main','{}')`,
      [company, branch],
    );
    await migration.query(
      "INSERT INTO settings(company_id,key,value) VALUES($1,'company',$2)",
      [company, company],
    );
    await migration.query(
      `INSERT INTO employees(company_id,id,code,email,employee_number,data)
      VALUES($1,'employee','001','same@example.test','EMP-000001','{}')`,
      [company],
    );
  }
}

it('applies versioned migrations once and rejects edited history', async () => {
  expect(await Promise.all([migrate(migration), migrate(migration)])).toEqual([
    [],
    [],
  ]);
  await migration.query(
    "UPDATE schema_migrations SET checksum='tampered' WHERE version=1",
  );
  await expect(migrate(migration)).rejects.toThrow('checksum changed');
  const { MIGRATIONS } = await import('../src/database/postgres/migrations.js');
  const { createHash } = await import('node:crypto');
  await migration.query(
    'UPDATE schema_migrations SET checksum=$1 WHERE version=1',
    [createHash('sha256').update(MIGRATIONS[0].sql).digest('hex')],
  );
});

it('enables and forces RLS on every company table under the actual restricted role', async () => {
  const tables = await migration.query(
    `SELECT relname,relrowsecurity,relforcerowsecurity
    FROM pg_class WHERE relnamespace='public'::regnamespace AND relname=ANY($1)`,
    [['companies', ...TENANT_TABLES]],
  );
  expect(tables.rows).toHaveLength(TENANT_TABLES.length + 1);
  expect(
    tables.rows.every((row) => row.relrowsecurity && row.relforcerowsecurity),
  ).toBe(true);
  await seed();
  expect((await runtime.query('SELECT * FROM employees')).rows).toEqual([]);
  await expect(
    runtime.query(
      `INSERT INTO settings(company_id,key,value) VALUES($1,'leak','x')`,
      [companyA],
    ),
  ).rejects.toMatchObject({ code: '42501' });
  await expect(runtime.query('TRUNCATE employees')).rejects.toMatchObject({
    code: '42501',
  });
  await expect(
    runtime.query('ALTER TABLE employees DISABLE ROW LEVEL SECURITY'),
  ).rejects.toMatchObject({
    code: '42501',
  });
  await expect(
    runtime.query('SELECT * FROM schema_migrations'),
  ).rejects.toMatchObject({ code: '42501' });
});

it('isolates reads and writes, including reused connections after commit and rollback', async () => {
  await seed();
  await store.companyTransaction(companyA, async (client) => {
    expect(
      (await client.query('SELECT company_id FROM employees')).rows,
    ).toEqual([{ company_id: companyA }]);
    expect(
      (
        await client.query('UPDATE settings SET value=$1 WHERE company_id=$2', [
          'bad',
          companyB,
        ])
      ).rowCount,
    ).toBe(0);
  });
  await expect(
    store.companyTransaction(companyA, async (client) => {
      await client.query("UPDATE settings SET value='rollback'");
      throw new Error('intentional rollback');
    }),
  ).rejects.toThrow('intentional rollback');
  await Promise.all(
    Array.from({ length: 12 }, (_, index) => {
      const company = index % 2 ? companyA : companyB;
      return store.companyTransaction(company, async (client) => {
        expect((await client.query('SELECT value FROM settings')).rows).toEqual(
          [{ value: company }],
        );
        await new Promise((resolve) => setTimeout(resolve, 2));
        expect(
          (await client.query('SELECT company_id FROM employees')).rows,
        ).toEqual([{ company_id: company }]);
      });
    }),
  );
  await expect(
    store.companyTransaction(companyA, async (client) => {
      await client.query(
        "INSERT INTO settings(company_id,key,value) VALUES($1,'forged','x')",
        [companyB],
      );
    }),
  ).rejects.toMatchObject({ code: '42501' });
  // Privileged migration credentials must never be accepted by the application transaction helper.
  const url = new URL(adminUrl);
  url.pathname = `/${database}`;
  const unsafe = new PostgresStore({ connectionString: url.href });
  try {
    await expect(
      unsafe.companyTransaction(companyA, async () => null),
    ).rejects.toThrow('non-privileged');
  } finally {
    await unsafe.close();
  }
  await expect(
    store.companyTransaction('not-a-uuid', async () => null),
  ).rejects.toThrow();
});

it('rejects cross-company references and preserves concurrent numbering and attendance uniqueness', async () => {
  await seed();
  await expect(
    store.companyTransaction(companyA, async (client) => {
      await client.query(
        `INSERT INTO employee_branches(company_id,employee_id,branch_id,effective_from)
      VALUES($1,'employee',$2,'2026-10-15')`,
        [companyA, branchB],
      );
    }),
  ).rejects.toMatchObject({ code: '23503' });
  const numbers = await Promise.all(
    Array.from({ length: 8 }, () =>
      concurrentStore.companyTransaction(companyA, async (client) => {
        const result = await client.query(
          `INSERT INTO settings(company_id,key,value)
      VALUES($1,'employee_number_sequence','1')
      ON CONFLICT(company_id,key) DO UPDATE SET value=(settings.value::bigint+1)::text RETURNING value`,
          [companyA],
        );
        return Number(result.rows[0].value);
      }),
    ),
  );
  expect(numbers.sort((a, b) => a - b)).toEqual([1, 2, 3, 4, 5, 6, 7, 8]);
  const results = await Promise.allSettled(
    [1, 2].map((id) =>
      concurrentStore.companyTransaction(companyA, async (client) => {
        await client.query(
          `INSERT INTO attendance(company_id,id,employee_id,work_date,check_in,schedule,timezone,branch_id,branch_snapshot)
      VALUES($1,$2,'employee','2026-10-15','2026-10-15T08:00:00Z','{}','Africa/Cairo',$3,'{}')`,
          [companyA, String(id), branchA],
        );
      }),
    ),
  );
  expect(
    results.filter((result) => result.status === 'fulfilled'),
  ).toHaveLength(1);
  expect(
    (await migration.query('SELECT count(*) FROM attendance')).rows[0].count,
  ).toBe('1');
});

it('keeps concurrent company contexts separate across physical connections', async () => {
  await seed();
  await Promise.all(
    Array.from({ length: 16 }, (_, index) => {
      const company = index % 2 ? companyA : companyB;
      return concurrentStore.companyTransaction(company, async (client) => {
        await client.query('SELECT pg_sleep(0.01)');
        expect(
          (await client.query('SELECT company_id FROM employees')).rows,
        ).toEqual([{ company_id: company }]);
      });
    }),
  );
});

